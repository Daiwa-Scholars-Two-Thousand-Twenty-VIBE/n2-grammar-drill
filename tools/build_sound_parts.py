#!/usr/bin/env python3
"""Builds js/sound.js: the sound part (音符) of each kanji in the kanji gap.

Many kanji are built from a meaning part and a sound part: 簡 has 門, read カン as in 間 and 関.
For each gap kanji whose on'yomi follows its sound part, js/sound.js keeps the part, the readings
the kanji shares with it, and other kanji on the same part that share that reading, with the
WaniKani level that teaches each one (so the drill can show the ones you already know).

    python3 -I tools/build_sound_parts.py          # run from the repo root

Sources:
- Kanjium (https://github.com/mifunetoshiro/kanjium) by Uros O., CC BY-SA 4.0, pinned to one
  commit. The phonetic components are his additions to KANJIDIC. js/sound.js keeps that licence.
- WaniKani levels: the public kanji pages on wanikani.com (six pages, no login). Older datasets
  are wrong for about 170 kanji since WaniKani's content updates.
"""
import datetime
import json
import os
import re
import sys
import time
import urllib.request

COMMIT = "9ebca4589565c696e7c39e089e2e928ad65f678c"
KANJIUM = f"https://raw.githubusercontent.com/mifunetoshiro/kanjium/{COMMIT}/data/source_files/"
WK_PAGES = [f"https://www.wanikani.com/kanji?difficulty={d}" for d in ("pleasant", "painful", "death", "hell", "paradise", "reality")]
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
KANJIDICT_COLS = ("kanji radical radvar phonetic idc type reg_on reg_kun onyomi kunyomi nanori strokes grade "
                  "jlpt kanken frequency meaning compact_meaning rtk1_3_old rtk1_3_new ko2001 ko2301 wrp_jkf wanikani").split()
FAMILY_MAX = 8


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "n2-grammar-drill build_sound_parts.py"})
    with urllib.request.urlopen(req) as r:
        return r.read().decode("utf-8")


def wk_levels():
    levels = {}
    pat = re.compile(
        r"header-title'>Level (\d+)<"
        r"|href=\"https://www\.wanikani\.com/kanji/[^\"]+\">\s*<div class=\"subject-character__content\">\s*"
        r"<span class=\"subject-character__characters\">\s*<span class=\"subject-character__characters-text\" lang=\"ja\">\s*(\S)\s*</span>"
    )
    for url in WK_PAGES:
        level = None
        for m in pat.finditer(fetch(url)):
            if m.group(1):
                level = int(m.group(1))
            elif level:
                levels[m.group(2)] = level
        time.sleep(1)
    if len(levels) < 2000:
        sys.exit(f"Only {len(levels)} kanji found on the WaniKani pages; the page layout may have changed.")
    return levels


def onyomi(row):
    # Jōyō readings when the kanji has them, otherwise every on'yomi without its (漢)(呉) tags.
    text = row["reg_on"] or re.sub(r"\(.\)", "", row["onyomi"])
    return [x.strip() for x in text.split("、") if x.strip()]


def main():
    gap = json.load(open(os.path.join(ROOT, "content", "kanji.json"), encoding="utf-8"))["kanji"]
    parts = {}
    for line in fetch(KANJIUM + "phonetics.txt").splitlines():
        p, readings, _count, _kind = line.split("\t")
        parts[p] = readings.split("、")
    rows = {}
    for line in fetch(KANJIUM + "kanjidict.txt").splitlines():
        row = dict(zip(KANJIDICT_COLS, line.split("\t")))
        rows[row["kanji"]] = row
    wk = wk_levels()

    out = {}
    for x in gap:
        row = rows.get(x["k"])
        part = row and row["phonetic"]
        if not part or part not in parts:
            continue
        shared = [r for r in x["on"] if r in parts[part]]
        if not shared:
            continue
        family = []
        for ch, r in rows.items():
            if ch == x["k"] or r["phonetic"] != part or not (ch in wk or r["grade"].startswith("Jōyō")):
                continue
            same = [o for o in onyomi(r) if o in shared]
            if same:
                family.append([ch, same[0], wk.get(ch, 0)])
        # The part itself first (it is the one to spot), then by WaniKani level; kanji WaniKani skips go last.
        family.sort(key=lambda f: (f[0] != part, f[2] == 0, f[2]))
        if family:
            out[x["k"]] = [part, shared, family[:FAMILY_MAX]]

    today = datetime.date.today().isoformat()
    lines = ",\n".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False, separators=(',', ':'))}" for k, v in out.items())
    js = f"""// Sound parts (音符) for the kanji gap. Generated by tools/build_sound_parts.py on {today}. Do not edit by hand.
// Adapted from the Kanjium database by Uros O. (https://github.com/mifunetoshiro/kanjium, commit {COMMIT[:7]}),
// licensed CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). This file is under the same licence.
// Changes: only kanji in content/kanji.json whose on'yomi follows the sound part; per kanji the part, the
// readings it shares with the part, and up to {FAMILY_MAX} other kanji on that part read the same way, with the
// WaniKani level that teaches each (from wanikani.com's public level pages, {today}; 0 = not in WaniKani).
// Kanjium draws on KANJIDIC by the Electronic Dictionary Research and Development Group (EDRDG licence).
// Each entry: kanji: [sound part, [shared on'yomi], [[kanji, reading, WaniKani level], ...]]
window.N2_SOUND = {{
{lines}
}};
"""
    with open(os.path.join(ROOT, "js", "sound.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print(f"js/sound.js: {len(out)} of {len(gap)} gap kanji have a sound part with a family", file=sys.stderr)


if __name__ == "__main__":
    main()
